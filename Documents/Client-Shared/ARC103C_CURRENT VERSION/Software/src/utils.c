/**************************************************************************************************
 * \fn 			
 * \brief
 *
 *************************************************************************************************/
void sleepms( int ms )
{
	int n;

	while( ms-- )
	{
		for( n=0;n<650;n++ );
	}
}

/**************************************************************************************************
 * \fn 			
 * \brief
 *
 *************************************************************************************************/
void sleep( int tm )
{
	long n;
	int i;

	for(i=0;i< tm; i++ )
	{
		n = 10000;
		while( n-- );
	}
}

/**************************************************************************************************
 * \fn 			
 * \brief
 *
 *************************************************************************************************/
void Mandatory_Wait( int seconds )
{
	sleep( seconds );
}

